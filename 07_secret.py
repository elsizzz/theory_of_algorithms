# Есть зашифрованное сообщение

secret_message = [
    'квевтфпп6щ3стмзалтнмаршгб5длгуча',
    'дьсеы6лц2бане4т64ь4б3ущея6втщл6б',
    'т3пплвце1н3и2кд4лы12чф1ап3бкычаь',
    'ьд5фму3ежородт9г686буиимыкучшсал',
    'бсц59мегщ2лятьаьгенедыв9фк9ехб1а',
]

# Расшифровка по строкам:
# 1. 4-я буква (индекс 3) -> 'в'
word1 = secret_message[0][3]

# 2. Буквы с 10 по 13 включительно (индексы 9:13) -> 'бане'
word2 = secret_message[1][9:13]

# 3. Буквы с 6 по 15 включительно через одну (индексы 5:15:2) -> 'велик'
word3 = secret_message[2][5:15:2]

# 4. Буквы с 8 по 13 включительно в обратном порядке (индексы с 12 по 7 с шагом -1) -> 'дороже'
word4 = secret_message[3][12:6:-1]

# 5. Буквы с 17 по 21 включительно в обратном порядке (индексы с 20 по 16 с шагом -1) -> 'негод'
# В строке 'бсц59мегщ2лятьаьгенедыв9фк9ехб1а' буквы 17-21: 'г', 'е', 'н', 'е', 'д' -> в обратном порядке 'денег'
word5 = secret_message[4][20:15:-1]

# Вывод расшифрованной фразы
print(f'{word1} {word2} {word3} {word4} {word5}')